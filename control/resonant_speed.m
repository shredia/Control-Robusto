function [T_res, error_res, wr, T_inphase, T_quadrature] = ...
    resonant_speed(Wm_ref, Wm, params)

% =========================================================================
% CONTROL RESONANTE DE VELOCIDAD CON COMPENSACION DE FASE
%
% Resonador:
%
%                    2*Kr*wc*(s*cos(phi) - wr*sin(phi))
% Gres(s) = -----------------------------------------------------
%                       s^2 + 2*wc*s + wr^2
%
%
% En la frecuencia resonante:
%
%       angle(Gres(j*wr)) ~= phi
%
%
% Para:
%
%       phi = 0
%
% recuperamos:
%
%                    2*Kr*wc*s
% Gres(s) = -----------------------------
%             s^2 + 2*wc*s + wr^2
%
% =========================================================================


% =========================================================================
% 0. PARAMETROS
% =========================================================================

Ts = params.Ts;

enable = params.enable;

Nc = params.Nc;

Kr = params.Kr;

wc = params.wc;

phi = params.phi;

T_res_max = params.T_res_max;

wr_min = params.wr_min;

wr_max = params.wr_max;


% =========================================================================
% 1. ESTADOS
% =========================================================================

persistent e_z1
persistent e_z2

persistent y_z1
persistent y_z2


if isempty(e_z1)

    e_z1 = 0.0;
    e_z2 = 0.0;

    y_z1 = 0.0;
    y_z2 = 0.0;

end


% =========================================================================
% 2. PROTECCIONES
% =========================================================================

Ts = max(Ts,1e-9);

Nc = abs(Nc);

wc = max(abs(wc),1e-6);

T_res_max = max(abs(T_res_max),0.0);

wr_min = max(abs(wr_min),0.0);

wr_max = max(abs(wr_max),wr_min);


% =========================================================================
% 3. ERROR
% =========================================================================

error_res = ...
    Wm_ref - Wm;


% =========================================================================
% 4. FRECUENCIA RESONANTE
% =========================================================================

wr = ...
    Nc * abs(Wm);


wr = ...
    min( ...
    max(wr,wr_min), ...
    wr_max);


% =========================================================================
% 5. SALIDAS
% =========================================================================

T_res = 0.0;

T_inphase = 0.0;

T_quadrature = 0.0;


% =========================================================================
% 6. RESONADOR
% =========================================================================

if enable == 1

    % ---------------------------------------------------------------------
    % Tustin
    % ---------------------------------------------------------------------

    Kt = ...
        2.0/Ts;


    % ---------------------------------------------------------------------
    % Denominador
    %
    % s² + 2*wc*s + wr²
    % ---------------------------------------------------------------------

    a0 = ...
          Kt*Kt ...
        + 2.0*wc*Kt ...
        + wr*wr;


    a1 = ...
        -2.0*Kt*Kt ...
        + 2.0*wr*wr;


    a2 = ...
          Kt*Kt ...
        - 2.0*wc*Kt ...
        + wr*wr;


    % =====================================================================
    % NUMERADOR CON COMPENSACION DE FASE
    %
    %       2*Kr*wc*(s*cos(phi) - wr*sin(phi))
    %
    % Separamos:
    %
    %       A*s + B
    %
    % con:
    %
    %       A =  2*Kr*wc*cos(phi)
    %
    %       B = -2*Kr*wc*wr*sin(phi)
    %
    % =====================================================================

    A = ...
        2.0 ...
        * Kr ...
        * wc ...
        * cos(phi);


    B = ...
        -2.0 ...
        * Kr ...
        * wc ...
        * wr ...
        * sin(phi);


    % ---------------------------------------------------------------------
    % Numerador discretizado
    % ---------------------------------------------------------------------

    b0 = ...
        A*Kt + B;


    b1 = ...
        2.0*B;


    b2 = ...
        -A*Kt + B;


    % =====================================================================
    % ECUACION EN DIFERENCIAS
    % =====================================================================

    T_res_raw = ...
        ( ...
          b0 * error_res ...
        + b1 * e_z1 ...
        + b2 * e_z2 ...
        - a1 * y_z1 ...
        - a2 * y_z2 ...
        ) ...
        / a0;


    % =====================================================================
    % SATURACION
    % =====================================================================

    T_res = ...
        min( ...
        max(T_res_raw,-T_res_max), ...
        T_res_max);


    % =====================================================================
    % MONITOREO
    %
    % OJO:
    %
    % Estas NO son componentes I/Q matematicamente exactas.
    % =====================================================================

    T_inphase = ...
        T_res;


    T_quadrature = ...
        y_z1;


    % =====================================================================
    % ACTUALIZACION
    % =====================================================================

    e_z2 = ...
        e_z1;


    e_z1 = ...
        error_res;


    y_z2 = ...
        y_z1;


    y_z1 = ...
        T_res;


else

    T_res = 0.0;

    T_inphase = 0.0;

    T_quadrature = 0.0;


    e_z1 = 0.0;
    e_z2 = 0.0;

    y_z1 = 0.0;
    y_z2 = 0.0;

end


end