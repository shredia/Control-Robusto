    Resultados.Phi_M1_deg, ...
    Resultados.RMSE_Wm_M1, ...
    '-o', ...
    'LineWidth',1.5);


hold on;


plot( ...
    Resultados.Phi_M1_deg, ...
    Resultados.RMSE_Wm_M2, ...
