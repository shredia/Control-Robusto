    'M1 - Wm observada', ...
    'M2 - Wm real', ...
    'Location','best');


title( ...
    'Fase efectiva del torque resonante');


hold off;


%% ========================================================================
% GRÁFICO 3
% FASE Wm OBSERVADA / REAL
% ========================================================================

figure;


plot( ...
    Resultados.Phi_M1_deg, ...
    Resultados.Fase_Wm_M1_deg, ...
